import asyncio, json
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox","--autoplay-policy=no-user-gesture-required"])
        errs=[]
        async def mk(w,h,dpr):
            ctx = await b.new_context(viewport={"width":w,"height":h}, device_scale_factor=dpr, has_touch=True, is_mobile=True)
            pg = await ctx.new_page()
            pg.on("console", lambda m: errs.append(m.text) if m.type=="error" else None)
            pg.on("pageerror", lambda e: errs.append(str(e)))
            await pg.goto("file:///home/claude/game/index.html"); await pg.wait_for_timeout(500)
            return ctx,pg
        ev=lambda pg,s: pg.evaluate(s)
        # ---- portrait phone, fresh install, touch
        ctx,pg = await mk(412,915,2.625)
        print("boot stack", await ev(pg,"[...__game.stack]"), "cont visible", await ev(pg,"getComputedStyle(tcont).display"), "new label", await ev(pg,"tnew.textContent"))
        await pg.screenshot(path="v2_title.png")
        await pg.tap("#tnew"); await pg.wait_for_timeout(300); await pg.tap("#bdone"); await pg.wait_for_timeout(200)
        print("after start stack", await ev(pg,"[...__game.stack]"), "started", await ev(pg,"__game.S.started"), "audio", await ev(pg,"!!(window.AudioContext)"))
        await pg.tap("#mbtn"); await pg.tap("#pset"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="v2_settings.png")
        # touch + / - on music row, toggle fixed stick, left hand, large
        rows = await pg.query_selector_all("#srows .srow")
        async def plus(i,n=1):
            for _ in range(n): await (await rows[i].query_selector_all(".pm"))[1].tap()
        await plus(0,2); await plus(3); await plus(4); await plus(5)
        print("cfg after touch", await ev(pg,"JSON.stringify(__game.CFG)"))
        await pg.tap("#sback"); await pg.tap("#presume"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="v2_fixed_lefty.png")
        # fixed stick drag (stick on right in lefty mode)
        sx = await ev(pg,"[parseFloat(stick.style.left),parseFloat(stick.style.top)]")
        cdp=await ctx.new_cdp_session(pg); x0=await ev(pg,"__game.S.x")
        await cdp.send("Input.dispatchTouchEvent",{"type":"touchStart","touchPoints":[{"x":sx[0],"y":sx[1]}]})
        await cdp.send("Input.dispatchTouchEvent",{"type":"touchMove","touchPoints":[{"x":sx[0]+50,"y":sx[1]}]})
        await pg.wait_for_timeout(500); await cdp.send("Input.dispatchTouchEvent",{"type":"touchEnd","touchPoints":[]})
        print("fixed stick moved", round(x0), round(await ev(pg,"__game.S.x")))
        await pg.reload(); await pg.wait_for_timeout(400)
        print("reload: cfg kept", await ev(pg,"[__game.CFG.music,__game.CFG.stick,__game.CFG.hand,__game.CFG.size]"), "continue shown", await ev(pg,"getComputedStyle(tcont).display"), await ev(pg,"tnew.textContent"))
        await ctx.close()
        # ---- landscape handheld (Retroid-like), controller only through the native bridge
        ctx,pg = await mk(640,360,3)
        async def press(i,hold=60):
            await ev(pg,f"__padKey({i},1)"); await pg.wait_for_timeout(hold); await ev(pg,f"__padKey({i},0)"); await pg.wait_for_timeout(60)
        await ev(pg,"__padName('Xbox Wireless Controller')")
        await press(4); await pg.wait_for_timeout(100)
        await pg.screenshot(path="v2_land_title.png")
        print("pad on", await ev(pg,"__game.PAD.on"), "keymode", await ev(pg,"document.body.className"), "focus", await ev(pg,"document.querySelector('.foc').id"))
        await press(0); await pg.wait_for_timeout(200)   # A on Start
        print("pad start -> stack", await ev(pg,"[...__game.stack]"), "hud", await ev(pg,"jbtn.textContent+' | '+mbtn.textContent"))
        x0=await ev(pg,"__game.S.x"); await ev(pg,"__padAxes(1,0,0,0,0,0)"); await pg.wait_for_timeout(500); await ev(pg,"__padAxes(0.05,0.02,0,0,0,0)"); await pg.wait_for_timeout(200)
        x1=await ev(pg,"__game.S.x"); await pg.wait_for_timeout(300); x2=await ev(pg,"__game.S.x")
        print("stick moved", round(x0),round(x1),"stops in deadzone", round(x2)==round(x1))
        await ev(pg,"__padAxes(0,0,0,1,0,0)"); await pg.wait_for_timeout(300); await ev(pg,"__padAxes(0,0,0,0,0,0)")
        print("dpad hat moved y", await ev(pg,"__game.S.y>27*16+12"))
        await pg.screenshot(path="v2_land_play.png")
        # sign: walk to it and press A
        await ev(pg,"__game.S.x=16*16+8;__game.S.y=27*16+8"); await pg.wait_for_timeout(100); await press(0)
        print("dialog", await ev(pg,"dialog.style.display+' / '+dhint.textContent")); await press(1)
        print("B closes dialog", await ev(pg,"dialog.style.display"))
        await press(3); print("Y journal", await ev(pg,"[...__game.stack]"))
        await press(15); await press(13); await pg.wait_for_timeout(100)
        await pg.screenshot(path="v2_land_journal.png")
        print("journal info", await ev(pg,"jinfo.textContent.slice(0,40)"))
        await press(1); await press(9); print("Start pause", await ev(pg,"[...__game.stack]"))
        await press(13); await press(13); await press(0); print("-> ", await ev(pg,"[...__game.stack]"))
        await press(14); await press(14); print("music via left x2", await ev(pg,"__game.CFG.music"))
        # go down to Action remap row and rebind to X(2)
        for _ in range(8): await press(13)
        print("focus row", await ev(pg,"document.querySelector('.foc').textContent"))
        await press(0); print("listening", await ev(pg,"__game.PAD.listen")); await press(2)
        print("bind", await ev(pg,"JSON.stringify(__game.CFG.bind)"), "row", await ev(pg,"document.querySelector('.foc').textContent"))
        await pg.screenshot(path="v2_land_settings.png")
        await press(1); await press(1); print("back x2", await ev(pg,"[...__game.stack]"))
        await ev(pg,"__back()"); print("android back opens pause", await ev(pg,"[...__game.stack]"))
        for _ in range(3): await press(13)
        await press(2); print("title via X confirm", await ev(pg,"[...__game.stack]"))
        await press(13); await press(2); print("new game asks", await ev(pg,"[...__game.stack]"), await ev(pg,"ctext.textContent"))
        await press(1); print("cancel", await ev(pg,"[...__game.stack]"))
        print("audio state", await ev(pg,"window.AudioContext?1:0"))
        print("errors", errs); await b.close()
asyncio.run(main())
